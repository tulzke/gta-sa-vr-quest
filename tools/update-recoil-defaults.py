"""Generate the native recoil table from the canonical, portable Quest config."""
from pathlib import Path
import argparse
import math

ROOT = Path(__file__).resolve().parents[1]
SUPPORTED = set(range(22, 35)) | {38}


def generate():
    profiles, disarm = {}, {}
    level = None
    for line in (ROOT / 'defaults/quest/recoil.ini').read_text(encoding='utf8').splitlines():
        fields = line.split()
        if not fields or fields[0].startswith('#'):
            continue
        if fields[0] == 'physical_recoil_level':
            assert len(fields) == 2 and level is None
            level = int(fields[1])
            assert 0 <= level <= 3
            continue
        key = tuple(map(int, fields[1:3]))
        assert key[0] in SUPPORTED and 0 <= key[1] <= 2
        if fields[0] == 'recoil_weapon_skill':
            assert len(fields) == 7 and key not in profiles
            values = tuple(map(float, fields[3:]))
            assert all(math.isfinite(v) and 0 <= v <= bound
                       for v, bound in zip(values, (45, 20, 200, 100)))
            profiles[key] = values
        elif fields[0] == 'recoil_one_hand_disarm':
            assert len(fields) == 4 and key not in disarm and fields[3] in ('0', '1')
            disarm[key] = int(fields[3])
        else:
            raise ValueError(f'Unexpected config row: {line}')
    expected = {(weapon, skill) for weapon in SUPPORTED for skill in range(3)}
    assert set(profiles) == set(disarm) == expected and level is not None
    rows = ['// Generated by tools/update-recoil-defaults.py; edit defaults/quest/recoil.ini.',
            f'constexpr int kDefaultRecoilLevel = {level};',
            'struct CapturedRecoil { int type, skill; Tuning tuning; };',
            'constexpr CapturedRecoil kCapturedRecoil[] = {']
    for key in sorted(profiles):
        values = ', '.join(f'{value:.1f}f' for value in profiles[key])
        rows.append('    {%d, %d, {%s, %s}},' % (*key, values, 'true' if disarm[key] else 'false'))
    return '\n'.join(rows + ['};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'native/src/DefaultRecoilCalibration.inl'
    generated = generate()
    if args.check:
        assert target.read_text(encoding='utf8') == generated, 'Native recoil defaults are stale'
        print('PASS: all 42 native recoil profiles match the canonical config')
    else:
        target.write_text(generated, encoding='utf8', newline='\n')
        print(f'Generated {target}')
